let lang = 'sv';
try {
  const saved = localStorage.getItem('tabelltraning_lang');
  if (saved === 'sv' || saved === 'en') lang = saved;
} catch (e) { /* localStorage unavailable — fall back to default */ }

export function getLang() {
  return lang;
}

export function setLang(newLang) {
  lang = newLang;
  try { localStorage.setItem('tabelltraning_lang', lang); } catch (e) { /* ignore */ }
}

export function t() {
  return I18N[lang];
}
